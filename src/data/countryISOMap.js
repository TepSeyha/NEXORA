// ⭐ មុខងារស្វែងរក ISO
export function getCountryISO(name) {
  if (!name) return null;

  // សាកល្បងដោយផ្ទាល់
  if (COUNTRY_ISO_MAP[name]) return COUNTRY_ISO_MAP[name];

  // សាកល្បង case-insensitive
  const lowerName = name.toLowerCase();
  for (const [key, value] of Object.entries(COUNTRY_ISO_MAP)) {
    if (key.toLowerCase() === lowerName) return value;
  }

  // សាកល្បងជាមួយឈ្មោះផ្សេង
  const variations = [
    name.replace('Republic of ', ''),
    name.replace('The ', ''),
    name.split(',')[0],
    name.split('(')[0].trim(),
    name.replace(' of America', '')
  ];

  for (const variant of variations) {
    if (COUNTRY_ISO_MAP[variant]) return COUNTRY_ISO_MAP[variant];
    const lower = variant.toLowerCase();
    for (const [key, value] of Object.entries(COUNTRY_ISO_MAP)) {
      if (key.toLowerCase() === lower) return value;
    }
  }

  return null;
}